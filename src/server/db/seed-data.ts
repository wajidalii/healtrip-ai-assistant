type Base = Pick<
  Provider,
  | "id"
  | "nameEn"
  | "nameAr"
  | "specialties"
  | "city"
  | "country"
  | "languages"
  | "rating"
  | "priceTier"
  | "descriptionEn"
  | "descriptionAr"
> &
  Partial<
    Pick<
      Provider,
      "emergencyCapable" | "telemedicine" | "acceptsInternational" | "accreditations" | "isActive"
    >
  >;

const facility = (kind: "hospital" | "clinic", p: Base): Provider => ({
  kind,
  parentProviderId: null,
  emergencyCapable: p.emergencyCapable ?? false,
  telemedicine: p.telemedicine ?? false,
  acceptsInternational: p.acceptsInternational ?? true,
  accreditations: p.accreditations ?? [],
  isActive: p.isActive ?? true,
  ...p,
});

